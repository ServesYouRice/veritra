#!/usr/bin/env python3
"""Writes testing/vectors/c7-move-v1.json: the 128-byte wrap field of a C7
`move` record and the compact move record that carries it
(docs/designs/C7-channel-history.md, decision 11; docs/crypto.md, "C7
move wrap"), built here independently of the Rust, Go and Dart code that
check it. Standard library only; `python3 testing/vectors/c7-move-v1.py`
rewrites the same file.

A narrowing move of a `full` channel wraps the old group's current
generation as `u64 E_prev | CHK_prev[32] | lp(prev_group_id) |
u64 E_prev_close`, zero-padded to 128 bytes; every other move carries 128
random bytes, which a receiver reads as "no wrap". A wrap is taken only
when it decodes and names the record's own old group and close epoch.
"""
import json
import os
import struct


def lp(value: bytes) -> bytes:
    return struct.pack(">H", len(value)) + value


def u64(value: int) -> bytes:
    return struct.pack(">Q", value)


def fill(seed: int, n: int) -> bytes:
    return bytes((seed + 7 * i) % 256 for i in range(n))


def wrap(prev_epoch: int, key: bytes, group: bytes, close_epoch: int) -> bytes:
    out = u64(prev_epoch) + key + lp(group) + u64(close_epoch)
    assert len(out) <= 114
    return out + bytes(128 - len(out))


old_group = ("conv_" + "2" * 32).encode()  # 37 bytes, as the server mints
long_group = b"g" * 64                     # the longest id: 114 bytes used
prev_key = fill(71, 32)

valid = [
    {
        "name": "server-length old group",
        "prev_epoch": 10, "prev_key_hex": prev_key.hex(),
        "prev_group_id": old_group.decode(), "prev_close_epoch": 20,
        "wrap_hex": wrap(10, prev_key, old_group, 20).hex(),
    },
    {
        "name": "64-byte old group, 114 bytes used",
        "prev_epoch": 0, "prev_key_hex": fill(3, 32).hex(),
        "prev_group_id": long_group.decode(), "prev_close_epoch": 0,
        "wrap_hex": wrap(0, fill(3, 32), long_group, 0).hex(),
    },
    {
        "name": "one-byte group, epochs near 2^53",
        "prev_epoch": 0x1F020304050607, "prev_key_hex": fill(5, 32).hex(),
        "prev_group_id": "g", "prev_close_epoch": 0x1F020304050608,
        "wrap_hex": wrap(0x1F020304050607, fill(5, 32), b"g",
                         0x1F020304050608).hex(),
    },
]

good = bytearray(wrap(10, prev_key, old_group, 20))
pad = bytearray(good)
pad[127] = 1
zero_key = bytearray(good)
zero_key[8:40] = bytes(32)
empty_id = u64(10) + prev_key + lp(b"") + u64(20)
long_id = u64(10) + prev_key + struct.pack(">H", 65) + b"g" * 65 + u64(20)
backwards = wrap(21, prev_key, old_group, 20)
invalid = [
    {"name": "all zero", "wrap_hex": bytes(128).hex()},
    {"name": "random bytes (a widening move)", "wrap_hex": fill(201, 128).hex()},
    {"name": "non-zero padding", "wrap_hex": bytes(pad).hex()},
    {"name": "zero key", "wrap_hex": bytes(zero_key).hex()},
    {"name": "empty group id", "wrap_hex": (empty_id + bytes(128 - len(empty_id))).hex()},
    {"name": "65-byte group id", "wrap_hex": long_id[:128].hex()},
    {"name": "opens after it closes", "wrap_hex": backwards.hex()},
    {"name": "127 bytes", "wrap_hex": bytes(good[:127]).hex()},
]

# The compact move record that carries the first valid wrap, as its
# channel message holds it: version 1 | u32 seq | prev[32] | u8 mode |
# u8 reason (2, move) | u64 close_epoch | key[32] | sig[64] |
# lp(close_group_id) | wrap[128].
new_key = fill(101, 32)
sig = fill(141, 64)
compact = (bytes([1]) + struct.pack(">I", 4) + fill(61, 32) + bytes([1, 2])
           + u64(20) + new_key + sig + lp(old_group)
           + bytes.fromhex(valid[0]["wrap_hex"]))
assert len(compact) == 143 + 2 + len(old_group) + 128

# A wrap is taken only for its own record: same old group, same close epoch.
mismatched = [
    {"name": "another old group",
     "wrap_hex": wrap(10, prev_key, ("conv_" + "7" * 32).encode(), 20).hex()},
    {"name": "another close epoch",
     "wrap_hex": wrap(10, prev_key, old_group, 19).hex()},
]

vector = {
    "version": 1,
    "description": (
        "C7 move wrap: u64 E_prev | CHK_prev[32] | lp(prev_group_id) | "
        "u64 E_prev_close, zero-padded to 128 bytes, in a compact move "
        "record after lp(close_group_id). Generated by c7-move-v1.py; Rust, "
        "Go and Dart check it."),
    "valid_wraps": valid,
    "invalid_wraps": invalid,
    "record": {
        "seq": 4, "prev_hex": fill(61, 32).hex(), "mode": 1, "reason": 2,
        "close_epoch": 20, "key_hex": new_key.hex(), "sig_hex": sig.hex(),
        "close_group_id": old_group.decode(),
        "wrap_hex": valid[0]["wrap_hex"],
        "compact_hex": compact.hex(),
        "compact_length": len(compact),
    },
    "mismatched_wraps": mismatched,
}
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "c7-move-v1.json")
with open(out, "w", encoding="utf-8") as handle:
    json.dump(vector, handle, indent=2)
    handle.write("\n")
