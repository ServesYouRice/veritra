#!/usr/bin/env python3
"""Offline fixture tests for the Dart dependency license gate."""

from __future__ import annotations

import contextlib
import importlib.util
import io
import json
import shutil
import subprocess
import tempfile
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parent
MODULE_PATH = SCRIPTS / "check-dart-licenses.py"
spec = importlib.util.spec_from_file_location("check_dart_licenses", MODULE_PATH)
assert spec and spec.loader
checker = importlib.util.module_from_spec(spec)
spec.loader.exec_module(checker)


class Fixture:
    """An app with a pub-written package configuration and lock file."""

    def __init__(self, temp: Path) -> None:
        self.temp = temp
        self.app = temp / "app"
        self.config = self.app / ".dart_tool/package_config.json"
        self.lock = self.app / "pubspec.lock"
        self.flutter = temp / "flutter"
        self.cache = temp / "pub-cache"
        self.entries: list[dict[str, object]] = [{"name": "app", "rootUri": "../", "packageUri": "lib/"}]
        self.lock_sources: dict[str, str] = {}
        self.extra: dict[str, object] = {"flutterRoot": self.flutter.as_uri()}
        (self.app / ".dart_tool").mkdir(parents=True)
        self.flutter.mkdir()
        (self.flutter / "LICENSE").write_text("Flutter BSD license\n", encoding="utf-8")

    def package(
        self,
        name: str,
        root: Path,
        source: str = "hosted",
        license_name: str | None = "LICENSE",
        uri: str | None = None,
    ) -> None:
        root.mkdir(parents=True, exist_ok=True)
        if license_name:
            (root / license_name).write_text("license\n", encoding="utf-8")
        self.entries.append({"name": name, "rootUri": uri or root.as_uri() + "/", "packageUri": "lib/"})
        self.lock_sources[name] = source

    def write(self) -> None:
        data = {"configVersion": 2, "packages": self.entries, **self.extra}
        self.config.write_text(json.dumps(data), encoding="utf-8")
        lines = ["# Generated by pub", "packages:"]
        for name, source in sorted(self.lock_sources.items()):
            lines += [f"  {name}:", "    dependency: transitive", f"    source: {source}", '    version: "1.0.0"']
        lines += ["sdks:", '  dart: ">=3.0.0 <4.0.0"']
        self.lock.write_text("\n".join(lines) + "\n", encoding="utf-8")

    def run(self, use_lock: bool = True) -> tuple[int, str, str]:
        args = ["--config", str(self.config)]
        if use_lock:
            args += ["--lock", str(self.lock)]
        stdout, stderr = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(stdout), contextlib.redirect_stderr(stderr):
            code = checker.main(args)
        return code, stdout.getvalue(), stderr.getvalue()


def fixture_test(test):
    def wrapper() -> None:
        with tempfile.TemporaryDirectory() as temp:
            test(Fixture(Path(temp)))

    wrapper.__name__ = test.__name__
    return wrapper


def hosted(fixture: Fixture, name: str, **kwargs: object) -> None:
    fixture.package(name, fixture.cache / "hosted/pub.dev" / f"{name}-1.0.0", **kwargs)


@fixture_test
def test_missing_config_fails(fixture: Fixture) -> None:
    code, _, stderr = fixture.run(use_lock=False)
    assert code == 1
    assert "run flutter pub get first" in stderr, stderr


@fixture_test
def test_empty_inventory_fails(fixture: Fixture) -> None:
    # Only the app itself: zero dependency packages is not a pass.
    fixture.write()
    assert fixture.run(use_lock=False)[0] == 1
    fixture.entries = []
    fixture.write()
    assert fixture.run(use_lock=False)[0] == 1


@fixture_test
def test_hosted_git_and_path_packages_are_checked(fixture: Fixture) -> None:
    hosted(fixture, "async")
    hosted(fixture, "collection", license_name="license.md")
    hosted(fixture, "meta", license_name="COPYING")
    # A path dependency, rootUri relative to the configuration file.
    fixture.package("local_pkg", fixture.temp / "packages/local_pkg", source="path", uri="../../packages/local_pkg/")
    # An unrelated, unlicensed pub-cache entry is not part of the inventory.
    (fixture.cache / "hosted/pub.dev/stale-9.9.9").mkdir(parents=True)
    fixture.write()
    code, stdout, stderr = fixture.run()
    assert code == 0, stderr
    assert "4 packages" in stdout, stdout

    # A git dependency without a license file fails and is named.
    fixture.package("git_pkg", fixture.cache / "git/git_pkg-0123abcd", source="git", license_name=None)
    fixture.write()
    code, _, stderr = fixture.run()
    assert code == 1
    assert "lacks a packaged license: git_pkg" in stderr, stderr


@fixture_test
def test_bad_package_roots_fail(fixture: Fixture) -> None:
    hosted(fixture, "async")
    fixture.entries.append({"name": "gone", "rootUri": (fixture.temp / "gone").as_uri() + "/"})
    fixture.lock_sources["gone"] = "hosted"
    fixture.write()
    code, _, stderr = fixture.run()
    assert code == 1 and "root is missing" in stderr, stderr

    fixture.entries[-1] = {"name": "gone", "rootUri": "https://example.invalid/gone/"}
    fixture.write()
    code, _, stderr = fixture.run()
    assert code == 1 and "not a local file" in stderr, stderr


@fixture_test
def test_malformed_configuration_fails(fixture: Fixture) -> None:
    hosted(fixture, "async")
    fixture.write()
    assert fixture.run()[0] == 0

    fixture.config.write_text("{not json", encoding="utf-8")
    assert fixture.run()[0] == 1

    fixture.extra["configVersion"] = 1
    fixture.write()
    assert fixture.run()[0] == 1
    del fixture.extra["configVersion"]

    # A configuration that does not contain the app is someone else's.
    fixture.entries = fixture.entries[1:]
    fixture.write()
    assert fixture.run()[0] == 1


@fixture_test
def test_configuration_must_match_the_lock(fixture: Fixture) -> None:
    hosted(fixture, "async")
    hosted(fixture, "meta")
    fixture.write()
    assert fixture.run()[0] == 0

    # A lock entry pub has not resolved yet (stale configuration).
    fixture.lock_sources["newer"] = "hosted"
    fixture.write()
    code, _, stderr = fixture.run()
    assert code == 1 and "not configured: newer" in stderr, stderr
    del fixture.lock_sources["newer"]

    # A configured package the lock does not list.
    del fixture.lock_sources["meta"]
    fixture.write()
    code, _, stderr = fixture.run()
    assert code == 1 and "not locked: meta" in stderr, stderr


@fixture_test
def test_sdk_packages_fall_back_to_the_sdk_license_visibly(fixture: Fixture) -> None:
    hosted(fixture, "async")
    fixture.package("flutter", fixture.flutter / "packages/flutter", source="sdk")
    fixture.package("flutter_test", fixture.flutter / "packages/flutter_test", source="sdk", license_name=None)
    fixture.write()
    code, stdout, stderr = fixture.run()
    assert code == 0, stderr
    assert "flutter_test: no license file in its package root" in stdout, stdout
    assert "UQ-005" in stdout
    assert "(1 via the Flutter SDK license)" in stdout, stdout

    # The lock must say the package comes from the SDK.
    fixture.lock_sources["flutter_test"] = "hosted"
    fixture.write()
    assert fixture.run()[0] == 1
    fixture.lock_sources["flutter_test"] = "sdk"

    # The SDK root must have its own license file.
    (fixture.flutter / "LICENSE").unlink()
    fixture.write()
    code, _, stderr = fixture.run()
    assert code == 1 and "lacks a packaged license: flutter_test" in stderr, stderr
    (fixture.flutter / "LICENSE").write_text("Flutter BSD license\n", encoding="utf-8")

    # Without flutterRoot there is no fallback at all.
    del fixture.extra["flutterRoot"]
    fixture.write()
    assert fixture.run()[0] == 1
    fixture.extra["flutterRoot"] = fixture.flutter.as_uri()

    # An unlicensed package outside the SDK gets no fallback, whatever the lock says.
    fixture.package("outside", fixture.temp / "elsewhere/outside", source="sdk", license_name=None)
    fixture.write()
    code, _, stderr = fixture.run()
    assert code == 1 and "lacks a packaged license: outside" in stderr, stderr


def test_shell_entry_point() -> None:
    with tempfile.TemporaryDirectory() as temp:
        root = Path(temp) / "repo"
        (root / "scripts").mkdir(parents=True)
        for name in ("check-dart-licenses.sh", "check-dart-licenses.py"):
            shutil.copy2(SCRIPTS / name, root / "scripts" / name)
        mobile = root / "mobile"
        mobile.mkdir()

        def run() -> subprocess.CompletedProcess[str]:
            # CI runs it from mobile/ as ../scripts/check-dart-licenses.sh.
            return subprocess.run(
                ["sh", "../scripts/check-dart-licenses.sh"], cwd=mobile, capture_output=True, text=True, check=False
            )

        missing = run()
        assert missing.returncode != 0
        assert "run flutter pub get first" in missing.stderr, missing.stderr

        package = Path(temp) / "cache/async-1.0.0"
        package.mkdir(parents=True)
        (package / "LICENSE").write_text("license\n", encoding="utf-8")
        (mobile / ".dart_tool").mkdir()
        (mobile / ".dart_tool/package_config.json").write_text(
            json.dumps(
                {
                    "configVersion": 2,
                    "packages": [
                        {"name": "private_messenger", "rootUri": "../"},
                        {"name": "async", "rootUri": package.as_uri() + "/"},
                    ],
                }
            ),
            encoding="utf-8",
        )
        (mobile / "pubspec.lock").write_text(
            "packages:\n  async:\n    dependency: transitive\n    source: hosted\n", encoding="utf-8"
        )
        passed = run()
        assert passed.returncode == 0, passed.stderr
        assert "1 packages" in passed.stdout, passed.stdout

        (package / "LICENSE").unlink()
        assert run().returncode == 1


if __name__ == "__main__":
    test_missing_config_fails()
    test_empty_inventory_fails()
    test_hosted_git_and_path_packages_are_checked()
    test_bad_package_roots_fail()
    test_malformed_configuration_fails()
    test_configuration_must_match_the_lock()
    test_sdk_packages_fall_back_to_the_sdk_license_visibly()
    test_shell_entry_point()
    print("Dart license gate fixture tests passed")
